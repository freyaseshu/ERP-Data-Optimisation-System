"""
Generates database/sample_data.sql with realistic ERP sample data:
  - 500 customers   (with ~15 intentional duplicate emails)
  - 200 products    (with ~10 intentional duplicate name/category/price)
  - Inventory records for every product (with a few duplicate rows)
  - 5,000 orders
  - 10,000+ order_items
  - 2 demo users (admin / analyst)

Run once with:  python database/generate_sample_data.py
Then load the result with:  SOURCE database/sample_data.sql;
"""
import random
from datetime import datetime, timedelta
from werkzeug.security import generate_password_hash

random.seed(42)

FIRST_NAMES = ["Aarav","Vivaan","Aditya","Vihaan","Arjun","Sai","Reyansh","Krishna","Ishaan","Rohan",
               "Ananya","Diya","Ira","Myra","Aadhya","Kiara","Saanvi","Anika","Riya","Meera",
               "John","Emma","Liam","Olivia","Noah","Ava","William","Sophia","James","Isabella"]
LAST_NAMES = ["Sharma","Verma","Gupta","Reddy","Iyer","Nair","Patel","Kumar","Singh","Rao",
              "Smith","Johnson","Brown","Davis","Miller","Wilson","Moore","Taylor","Anderson","Thomas"]
CITIES = ["Hyderabad","Bengaluru","Mumbai","Delhi","Chennai","Pune","Kolkata","Ahmedabad",
          "Jaipur","Lucknow","New York","London","Singapore","Toronto","Dubai"]
CATEGORIES = ["Electronics","Furniture","Clothing","Groceries","Stationery","Sports","Toys",
              "Books","Beauty","Automotive"]
PRODUCT_ADJ = ["Premium","Deluxe","Compact","Portable","Wireless","Smart","Eco","Classic","Pro","Mini"]
PRODUCT_NOUN = ["Chair","Table","Laptop","Phone","Backpack","Bottle","Lamp","Notebook","Headphones",
                "Shoes","Watch","Camera","Speaker","Monitor","Keyboard"]
WAREHOUSES = ["WH-North","WH-South","WH-East","WH-West","WH-Central"]
STATUSES = ["Pending","Processing","Shipped","Delivered","Cancelled"]


def esc(s):
    return str(s).replace("'", "''")


def rand_date(start_days_ago=1000, end_days_ago=0):
    days = random.randint(end_days_ago, start_days_ago)
    return (datetime.utcnow() - timedelta(days=days,
             hours=random.randint(0, 23), minutes=random.randint(0, 59)))


def sql_dt(dt):
    return dt.strftime('%Y-%m-%d %H:%M:%S')


lines = []
lines.append("-- =====================================================================")
lines.append("-- ERP Data Optimisation System - Sample Data")
lines.append("-- Auto-generated by database/generate_sample_data.py")
lines.append("-- Run AFTER schema.sql has created the tables.")
lines.append("-- =====================================================================\n")
lines.append("SET FOREIGN_KEY_CHECKS = 0;\n")

# ---------------------------------------------------------------------
# users
# ---------------------------------------------------------------------
lines.append("-- Demo users (password for both: Password123!)")
admin_hash = esc(generate_password_hash("Password123!"))
analyst_hash = esc(generate_password_hash("Password123!"))
lines.append(
    "INSERT INTO users (username, email, password, role) VALUES "
    f"('admin', 'admin@erp-demo.com', '{admin_hash}', 'Admin'),"
    f"('analyst', 'analyst@erp-demo.com', '{analyst_hash}', 'Analyst');\n"
)

# ---------------------------------------------------------------------
# customers  (500 total, ~15 intentional duplicate emails)
# ---------------------------------------------------------------------
NUM_CUSTOMERS = 500
customer_rows = []
used_emails = []
for i in range(1, NUM_CUSTOMERS + 1):
    fname = random.choice(FIRST_NAMES)
    lname = random.choice(LAST_NAMES)
    name = f"{fname} {lname}"
    email = f"{fname.lower()}.{lname.lower()}{i}@example.com"
    city = random.choice(CITIES)
    created = sql_dt(rand_date(900, 5))
    customer_rows.append((name, email, city, created))
    used_emails.append(email)

# Inject ~15 duplicate-email customers (reusing an existing email)
for _ in range(15):
    dup_email = random.choice(used_emails)
    fname = random.choice(FIRST_NAMES)
    lname = random.choice(LAST_NAMES)
    name = f"{fname} {lname}"
    city = random.choice(CITIES)
    created = sql_dt(rand_date(900, 5))
    customer_rows.append((name, dup_email, city, created))

lines.append(f"-- customers ({len(customer_rows)} rows, including intentional duplicates)")
lines.append("INSERT INTO customers (name, email, city, created_at) VALUES")
vals = [f"('{esc(n)}', '{esc(e)}', '{esc(c)}', '{d}')" for n, e, c, d in customer_rows]
lines.append(",\n".join(vals) + ";\n")
TOTAL_CUSTOMERS = len(customer_rows)

# ---------------------------------------------------------------------
# products (200 total, ~10 intentional duplicates on name+category+price)
# ---------------------------------------------------------------------
NUM_PRODUCTS = 200
product_rows = []
for i in range(1, NUM_PRODUCTS + 1):
    name = f"{random.choice(PRODUCT_ADJ)} {random.choice(PRODUCT_NOUN)}"
    category = random.choice(CATEGORIES)
    price = round(random.uniform(5, 2000), 2)
    created = sql_dt(rand_date(900, 5))
    product_rows.append((name, category, price, created))

# Inject ~10 exact duplicate products
for _ in range(10):
    dup = random.choice(product_rows[:NUM_PRODUCTS])
    created = sql_dt(rand_date(900, 5))
    product_rows.append((dup[0], dup[1], dup[2], created))

lines.append(f"-- products ({len(product_rows)} rows, including intentional duplicates)")
lines.append("INSERT INTO products (name, category, price, created_at) VALUES")
vals = [f"('{esc(n)}', '{esc(c)}', {p}, '{d}')" for n, c, p, d in product_rows]
lines.append(",\n".join(vals) + ";\n")
TOTAL_PRODUCTS = len(product_rows)

# ---------------------------------------------------------------------
# inventory (one record per product, plus a few duplicate rows)
# ---------------------------------------------------------------------
inventory_rows = []
for pid in range(1, TOTAL_PRODUCTS + 1):
    qty = random.randint(0, 500)
    wh = random.choice(WAREHOUSES)
    updated = sql_dt(rand_date(60, 0))
    inventory_rows.append((pid, qty, wh, updated))

# Inject a few duplicate inventory rows (same product_id + warehouse)
for _ in range(8):
    pid = random.randint(1, TOTAL_PRODUCTS)
    wh = random.choice(WAREHOUSES)
    qty = random.randint(0, 500)
    updated = sql_dt(rand_date(60, 0))
    inventory_rows.append((pid, qty, wh, updated))

lines.append(f"-- inventory ({len(inventory_rows)} rows, including intentional duplicates)")
lines.append("INSERT INTO inventory (product_id, quantity, warehouse_location, last_updated) VALUES")
vals = [f"({pid}, {q}, '{esc(w)}', '{d}')" for pid, q, w, d in inventory_rows]
lines.append(",\n".join(vals) + ";\n")

# ---------------------------------------------------------------------
# orders (5,000)
# ---------------------------------------------------------------------
NUM_ORDERS = 5000
order_rows = []
for i in range(1, NUM_ORDERS + 1):
    cid = random.randint(1, TOTAL_CUSTOMERS)
    odate = sql_dt(rand_date(1000, 0))
    status = random.choice(STATUSES)
    order_rows.append([cid, odate, 0.0, status])  # total_amount filled after items

lines.append(f"-- orders ({NUM_ORDERS} rows) -- total_amount is a placeholder, updated after order_items")
lines.append("INSERT INTO orders (customer_id, order_date, total_amount, status) VALUES")
vals = [f"({cid}, '{d}', 0.00, '{s}')" for cid, d, _, s in order_rows]
# MySQL has a max_allowed_packet limit; split into chunks of 1000
CHUNK = 1000
for start in range(0, len(vals), CHUNK):
    chunk_vals = vals[start:start + CHUNK]
    lines.append("INSERT INTO orders (customer_id, order_date, total_amount, status) VALUES\n" +
                  ",\n".join(chunk_vals) + ";")
lines.append("")

# ---------------------------------------------------------------------
# order_items (10,000+ ; 2-3 items per order on average)
# ---------------------------------------------------------------------
order_item_rows = []
order_totals = {}
for order_id in range(1, NUM_ORDERS + 1):
    num_items = random.randint(2, 4)
    total = 0.0
    for _ in range(num_items):
        pid = random.randint(1, TOTAL_PRODUCTS)
        qty = random.randint(1, 6)
        price = round(random.uniform(5, 2000), 2)
        order_item_rows.append((order_id, pid, qty, price))
        total += qty * price
    order_totals[order_id] = round(total, 2)

lines.append(f"-- order_items ({len(order_item_rows)} rows)")
vals = [f"({oid}, {pid}, {q}, {p})" for oid, pid, q, p in order_item_rows]
for start in range(0, len(vals), CHUNK):
    chunk_vals = vals[start:start + CHUNK]
    lines.append("INSERT INTO order_items (order_id, product_id, quantity, price) VALUES\n" +
                  ",\n".join(chunk_vals) + ";")
lines.append("")

# ---------------------------------------------------------------------
# Back-fill order totals to match their items
# ---------------------------------------------------------------------
lines.append("-- Recalculate order totals from their items (keeps data consistent)")
lines.append("""UPDATE orders o
JOIN (
    SELECT order_id, SUM(quantity * price) AS calc_total
    FROM order_items
    GROUP BY order_id
) t ON t.order_id = o.id
SET o.total_amount = t.calc_total;
""")

lines.append("SET FOREIGN_KEY_CHECKS = 1;")

with open("database/sample_data.sql", "w") as f:
    f.write("\n".join(lines))

print(f"Generated database/sample_data.sql")
print(f"  customers: {TOTAL_CUSTOMERS}")
print(f"  products:  {TOTAL_PRODUCTS}")
print(f"  inventory: {len(inventory_rows)}")
print(f"  orders:    {NUM_ORDERS}")
print(f"  order_items: {len(order_item_rows)}")
